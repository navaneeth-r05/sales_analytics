-- compare sales accross months
create or replace view acc_months as 
with comp_sales as (
select 
year(o.order_date) as years,
month(o.order_date) as months,
Round(sum(oi.quantity * oi.unit_price * (1-discount_pct /100)),2) as sales_accross_months,
monthname(o.order_date) as nameofmonth
from orders o
join order_items oi on 
oi.order_id = o.order_id
group by years,months,nameofmonth)

select years,
months,
sales_accross_months,
nameofmonth,
coalesce(concat('(cur) ',sales_accross_months,' - ',lead(sales_accross_months) over(order by years , months),' (next)'),sales_accross_months) as compare
from comp_sales
order by years,months; 

-- Now im going to find the percentage changes and whether it is increase or dedcrease  by using cte "comp_sales"  as "comp_sales_result"
create view sales_result as 
with comp_sales_result as (
select 
year(o.order_date) as years,
month(o.order_date) as months,
Round(sum(oi.quantity * oi.unit_price * (1-discount_pct /100)),2) as sales_accross_months,
monthname(o.order_date) as nameofmonth
from orders o
join order_items oi on 
oi.order_id = o.order_id
 where o.status in ('Shipped','Delivered')
group by years,months,nameofmonth),

with_prev_sales as (
	select * , lag(sales_accross_months) over (order by years,months ) as prev_sales
    from comp_sales_result
)	
select years,
months,
sales_accross_months,
nameofmonth,
prev_sales,
round((sales_accross_months - prev_sales) / nullif(prev_sales,0) *100 ,2) as percentage_change, 
case 
when sales_accross_months - prev_sales > 0 then 'Increase'
when sales_accross_months - prev_sales < 0 then 'Decrease'
when prev_sales is null then 'N/A'
end as trends 
from with_prev_sales
order by years,months;


-- Finding whether they reach thier target
-- first we need to find the total revenue and target revenue and then we compare 
-- here im taking already existing query for retrive total_revenue by each employee
-- this is for yearly 
create or replace view target_result as 
with total_revenue as(
select employee_id ,
sum(total_revenue) as total_revenue
from S_total
group by employee_id),

total_target as (
select employee_id ,
sum(target_amount) as total_target
from sales_targets
group by employee_id)

select tt.employee_id,
       concat(e.first_name, ' ', e.last_name) as employee_name,
	   coalesce(tr.total_revenue, 0) as total_revenue_emp,                                                 
       tt.total_target,
        round(coalesce(tr.total_revenue, 0) / tt.total_target * 100, 2) as percent_achieved,             -- here using coalesce helps to mark the percentage into 0 not null
       case when coalesce(tr.total_revenue, 0) >= tt.total_target
            then 'Yes' else 'No' end as target_status
from total_target tt	
join employees e on e.employee_id = tt.employee_id
left join total_revenue tr on tr.employee_id = tt.employee_id
order by percent_achieved;


