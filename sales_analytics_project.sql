from orders;

select * from Total_Transcations;                                                                       -- To view Total_Transcations



-- This query is for to calculate total sales,transaction count and revenue generated by each employees , departments and months 

-- description Here im using "CONCAT" to merging the first and last name and using "ROUND" for decimals and aggregate function "SUM" to calculate the total revenues and "COUNT" is for the total transcation by each
-- creating view to use this query for others
create or replace view s_total as 
select e.employee_id,
concat(e.first_name,' ',e.last_name) as employee_names,
d.dept_name as 'departments',
year(o.order_date) as order_year,
Month(o.order_date ) as order_month,
Round(sum(																						
		oi.quantity * oi.unit_price * (1-o.discount_pct /100)),2) as total_revenue,
count(distinct o.order_id ) AS total_transactions
from departments d
join employees e on 
e.department_id = d.department_id 
join orders o  on 
o.employee_id = e.employee_id 
join order_items oi on 
oi.order_id = o.order_id
where o.status in ('Shipped','Delivered')
group by e.employee_id , employee_names , d.dept_name , order_month , order_year;


-- now using S_total view to write Employee, department and transactions:

select employee_id,employee_names,departments,total_transactions
from s_total
order by total_transactions desc;

-- Each employee’s totals across all months:

select employee_id, employee_names, departments,
       sum(total_transactions) as total_transactions,
       sum(total_revenue)      as total_revenue
from s_total
group by employee_id, employee_names, departments
order by total_revenue desc;

-- Department totals:

select departments,
       sum(total_transactions) as total_transactions,
       sum(total_revenue)      as total_revenue
from s_total
group by departments;


-- Month totals: 

select order_year, order_month,
       sum(total_transactions) as total_transactions,
       sum(total_revenue)      as total_revenue
from s_total
group by order_year, order_month
order by order_year, order_month;


-- Now im going to find the top performing employee and rank the employee according to their sales revenue 
-- A CTE exists only for the single SQL statement in which you define it. After that statement finishes, the CTE name is no longer available.
-- but here im creating a view with view so each tym it will called when i select view 


create or replace view top_perf_result as 
with cte as (
select e.employee_id,
concat(first_name,' ',last_name) as employee_name,
Round(sum(oi.quantity * oi.unit_price * (1-discount_pct /100)),2) as sales_revenue           -- Using a CTE to separate employee revenue aggregation
from employees e 																			 -- from the ranking calculation, making the query easier to read.
join orders o on 
o.employee_id = e.employee_id 
join order_items oi on 
oi.order_id = o.order_id 
where o.status in ('Shipped','Delivered') 
group by e.employee_id,employee_name)

select employee_id,
employee_name,
sales_revenue,
rank() over(order by sales_revenue desc) sales_revenue_rank 
from cte; 
-- where sales_revenue <= 5 gives top 5 performance


select * from top_perf_result;		


