 p.employee_id = e.employee_id 
 group by e.employee_id,employee_name;
 
 
 -- Which employees have a high rating and also high sales?
-- here i used existing "s_total"' view table to write query easy 
 SELECT
    s.employee_id,
    s.employee_names,
    ROUND(AVG(p.rating), 2) AS avg_rating,
    MAX(s.total_revenue) AS total_revenue
FROM S_total s
JOIN performance_reviews p
    ON p.employee_id = s.employee_id
GROUP BY s.employee_id, s.employee_names
HAVING AVG(p.rating) >= 4
   AND MAX(s.total_revenue) >= 100000;
   
-- Whose rating went up over the quarters? (LAG again)
create or replace view over_quarter as 
with over_quater as(
select e.employee_id,  
CONCAT(e.first_name, ' ', e.last_name) AS employee_name,
p.review_year as review_year,
p.review_quarter as quarters,
p.rating as ratings,
LAG(p.rating) OVER (
            PARTITION BY p.employee_id
            ORDER BY p.review_year, p.review_quarter
        ) AS previous_rating
from employees e 
join performance_reviews p on
p.employee_id = e.employee_id )

select employee_id,
employee_name,
review_year,
quarters,
previous_rating,
ratings as current_rating
from over_quater
where ratings > previous_rating
order by employee_id,review_year,quarters;

-- view 
select * from over_quarter;