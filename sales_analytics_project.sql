-- calucluate the total sales 

create view Total_Revenue as 
select Round(sum(																						-- Here im caluculating the Total revenues by checking whether the status are ('Shipped','Delivered');
case when o.status in ('Shipped','Delivered') then oi.quantity * oi.unit_price end ),2) as Total        -- using Round() to give the Answer in a Expected Decimals 
from order_items oi  																					-- joining the orders and order_items to match revenue belongs to order_id		
join orders o on 
oi.order_id = o.order_id; 																				-- Finally im creating the view to see whenever we want

select * from Total_Revenue;  																			-- To view the Revenue

