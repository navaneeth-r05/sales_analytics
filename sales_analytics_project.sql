-- this is for monthly target -- --------------------------------------------------------------
create or replace view target_result_month as 
WITH monthly_revenue AS (
    SELECT
        o.employee_id,
        YEAR(o.order_date) AS target_year,
        MONTH(o.order_date) AS target_month,
        ROUND(
            SUM(
                oi.quantity * oi.unit_price
                * (1 - o.discount_pct / 100)
            ), 2
        ) AS total_revenue
    FROM orders o
    JOIN order_items oi
        ON oi.order_id = o.order_id
    WHERE o.status IN ('Shipped', 'Delivered')
    GROUP BY
        o.employee_id,
        YEAR(o.order_date),
        MONTH(o.order_date)
)
SELECT
    e.employee_id,
    CONCAT(e.first_name, ' ', e.last_name) AS employee_name,
    s.target_year,
    s.target_month,
    COALESCE(mr.total_revenue, 0) AS total_revenue,
    s.target_amount,
    ROUND(
        COALESCE(mr.total_revenue, 0)
        / s.target_amount * 100, 2
    ) AS achievement_percentage,																-- here using coalesce helps to mark the percentage into 0 not null
    CASE
        WHEN COALESCE(mr.total_revenue, 0) >= s.target_amount
        THEN 'Yes'
        ELSE 'No'
    END AS target_status
FROM sales_targets s
JOIN employees e
    ON e.employee_id = s.employee_id
LEFT JOIN monthly_revenue mr
    ON mr.employee_id = s.employee_id
    AND mr.target_year = s.target_year
    AND mr.target_month = s.target_month
ORDER BY
    s.target_year,
    s.target_month,
    e.employee_id;
    
-- view for target_result_month
select * from target_result_month;


